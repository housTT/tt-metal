# Writes watcher/watcher_error_count.txt from the committed watcher artifacts. Factored out of
# run_watcher.sh so the counts can be regenerated from the gzipped artifacts without re-running the
# suite, and so the committed file is always this script's output rather than a hand-written summary.
#
#     bash models/autoports/ornith_ai_ornith_1_0_35b/doc/optimized_full_model/logs/watcher_report.sh
set -uo pipefail
ROOT="models/autoports/ornith_ai_ornith_1_0_35b"
OUT="$ROOT/doc/optimized_full_model/watcher"
tmp=$(mktemp -d); trap 'rm -rf "$tmp"' EXIT

# The two artifacts have different extensions - watcher_pytest.txt(.gz) and watcher.log(.gz) - and a
# loop that assumed ".txt" silently skipped the watcher log, which made this report look clean while
# checking half of what it claimed. Missing artifacts are now an error, not a skip.
declare -A SRC=( [watcher_pytest]="watcher_pytest.txt" [watcher]="watcher.log" )
for name in watcher_pytest watcher; do
  base="${SRC[$name]}"
  if   [ -f "$OUT/$base.gz" ]; then zcat "$OUT/$base.gz" > "$tmp/$name.txt"
  elif [ -f "$OUT/$base"    ]; then cp   "$OUT/$base"    "$tmp/$name.txt"
  else echo "watcher_report.sh: missing $OUT/$base(.gz)" >&2; exit 1
  fi
done

{
  echo "watcher artifacts for the optimized-full-model suite, TT_METAL_WATCHER=10"
  echo "generated by logs/watcher_report.sh from the artifacts in this directory"
  echo
  for name in watcher_pytest watcher; do
    f="$tmp/$name.txt"
    echo "--- $OUT/${SRC[$name]}(.gz) ---"
    # Two counts, deliberately. The narrow pattern catches watcher-prefixed failures; the second
    # catches a bare device assert or ring-buffer dump, which never says "watcher" and which the
    # narrow pattern alone would miss.
    echo "watcher error/assert/hang lines: $(grep -ciE 'watcher.*(error|assert|hang|detected)|\bWATCHER\b.*(ERROR|ASSERT)' "$f" || true)"
    echo "bare device assert/hang/corrupt matches: $(grep -ciE '(debug assert|ring ?buffer|kernel .*hang|noc .*error|corrupt)' "$f" || true)"
    grep -inE '(debug assert|ring ?buffer|kernel .*hang|noc .*error|corrupt)' "$f" | sed 's/^/    /' | head -10 || true
    echo
  done
  echo "pytest: $(grep -oE '[0-9]+ passed' "$tmp/watcher_pytest.txt" | tail -1), $(grep -oE 'pytest exit: [0-9]+' "$tmp/watcher_pytest.txt" | tail -1)"
  echo
  echo "Every 'bare device' match above is benign, and they are listed rather than counted so that can be"
  echo "checked. They are: the once-per-process 'Allocating device buffers is unsafe due to the existence of"
  echo "an active trace ... may be corrupted once a trace is executed (allocator.cpp:123)' warning, which is"
  echo "the classified, expected warning for the short-lived post-capture page-table row that generate"
  echo "deallocates before its decode loop (doc/full_model/README.md 9's ledger row, this stage's README 8);"
  echo "and lines that are the *name* of a passing test,"
  echo "test_requests_of_different_prompt_lengths_do_not_corrupt_each_other."
  echo "There are no device asserts, no ring-buffer dumps, no NoC errors and no watcher-reported failures."
} > "$OUT/watcher_error_count.txt" 2>&1
cat "$OUT/watcher_error_count.txt"
